CREATE SEQUENCE MQ_MESSAGE_SEQ START WITH 1 INCREMENT BY 50 CACHE 1000;

CREATE TABLE MQ_MESSAGE (
    ID              NUMBER(19)                  NOT NULL,
    MESSAGE_ID      VARCHAR2(100)               NOT NULL,
    CORRELATION_ID  VARCHAR2(100),
    QUEUE_NAME      VARCHAR2(48)                NOT NULL,
    PAYLOAD         CLOB,
    PUT_TIMESTAMP   TIMESTAMP(6) WITH TIME ZONE,
    RECEIVED_AT     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT PK_MQ_MESSAGE PRIMARY KEY (ID),
    CONSTRAINT UK_MQ_MESSAGE_MESSAGE_ID UNIQUE (MESSAGE_ID)
);

CREATE INDEX IDX_MQ_MESSAGE_RECEIVED_AT ON MQ_MESSAGE (RECEIVED_AT);
CREATE INDEX IDX_MQ_MESSAGE_CORRELATION_ID ON MQ_MESSAGE (CORRELATION_ID);